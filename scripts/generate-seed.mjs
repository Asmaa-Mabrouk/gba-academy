// Generates services/api/src/main/resources/db/migration/V2__sample_data.sql from the web app's sample data,
// so the mock mode and the real database always show the same catalogue.
// Usage: node scripts/generate-seed.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { tmpdir } from "node:os";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tmp = join(tmpdir(), "gba-seed");
mkdirSync(tmp, { recursive: true });
writeFileSync(join(tmp, "mock-data.ts"), readFileSync(join(root, "apps/web/src/lib/mock-data.ts"), "utf8").replace('from "./types"', 'from "./types.ts"'));
writeFileSync(join(tmp, "types.ts"), "export {};\n");
const { COURSES, MENTORS, REVIEWS } = await import(pathToFileURL(join(tmp, "mock-data.ts")).href);

const q = (s) => (s == null ? "NULL" : `'${String(s).replace(/'/g, "''")}'`);
const j = (o) => `${q(JSON.stringify(o))}::jsonb`;
const arr = (a) => `ARRAY[${a.map(q).join(",")}]::text[]`;
const out = ["-- GENERATED by scripts/generate-seed.mjs. Do not edit by hand. Sample data only.\n"];

for (const m of MENTORS)
  out.push(`INSERT INTO mentors(id,slug,name,title,bio,expertise,languages,hue,rating,review_count,learners) VALUES (${q(m.id)},${q(m.slug)},${j(m.name)},${j(m.title)},${j(m.bio)},${arr(m.expertise)},${arr(m.languages)},${m.hue},${m.rating},${m.reviewCount},${m.learners});`);
for (const c of COURSES) {
  out.push(`INSERT INTO courses(id,slug,audience,level,topic,title,subtitle,description,outcomes,modules,mentor_id,hours,languages,featured,is_new,bestseller,age_range,certificate,cpd_points,rating,review_count,learners) VALUES (${q(c.id)},${q(c.slug)},${q(c.audience)},${q(c.level)},${q(c.topic)},${j(c.title)},${j(c.subtitle)},${j(c.description)},${j(c.outcomes)},${j(c.modules)},${q(c.mentorId)},${c.hours},${arr(c.languages)},${c.featured},${c.isNew},${c.bestseller},${q(c.ageRange)},${c.certificate},${c.cpdPoints ?? "NULL"},${c.rating},${c.reviewCount},${c.learners});`);
  for (const o of c.offerings) {
    out.push(`INSERT INTO offerings(id,course_id,mode,price_halalas,compare_at_halalas,access_days,cohort_label) VALUES (${q(o.id)},${q(c.id)},${q(o.mode)},${o.priceHalalas},${o.compareAtHalalas ?? "NULL"},${o.accessDays ?? "NULL"},${o.cohortLabel ? j(o.cohortLabel) : "NULL"});`);
    for (const s of o.sessions)
      out.push(`INSERT INTO live_sessions(id,offering_id,starts_at,duration_min,seats,seats_taken,title) VALUES (${q(s.id)},${q(o.id)},${q(s.startsAt)},${s.durationMin},${s.seats},${s.seats - s.seatsLeft},${j(s.title)});`);
  }
}
for (const r of REVIEWS)
  out.push(`INSERT INTO reviews(id,course_id,user_id,author,rating,comment,mentor_reply,created_at) VALUES (${q(r.id)},${q("c-" + r.courseSlug)},NULL,${q(r.author)},${r.rating},${j(r.comment)},${r.mentorReply ? j(r.mentorReply) : "NULL"},${q(r.createdAt)});`);

const file = join(root, "services/api/src/main/resources/db/migration/V2__sample_data.sql");
writeFileSync(file, out.join("\n") + "\n");
console.log(`wrote ${file}: ${MENTORS.length} mentors, ${COURSES.length} courses, ${REVIEWS.length} reviews`);
