def check(id, name, cond, detail=""):
    results.append({"id": id, "name": name, "pass": bool(cond), "detail": str(detail)[:300]})
    print(("PASS " if cond else "FAIL ") + id + "  " + name + ("" if cond else "   -> " + str(detail)[:220]), flush=True)

def goto(pg, path, wait=400):
    pg.goto(BASE + path); pg.wait_for_load_state("networkidle"); pg.wait_for_timeout(wait)

def login(pg, email, pw, loc="en"):
    goto(pg, f"/{loc}/login", 200)
    pg.locator("input[type=email]").fill(email); pg.locator("input[autocomplete=current-password]").fill(pw)
    pg.locator("form button.btn-gold").click(); pg.wait_for_timeout(700)

def logout(pg):
    pg.evaluate("localStorage.removeItem('gba.token'); localStorage.removeItem('gba.cart')")

def body(pg): return pg.locator("body").inner_text()

def scenario(id, fn, *a):
    try: fn(*a)
    except Exception as e:
        check(id, "scenario crashed", False, repr(e).replace("\n", " ")[:260])
        try: a[0].screenshot(path=os.path.join(OUT, f"{id}-crash.png"))
        except Exception: pass

def bi(pg, label, ar, en):
    """Fill a bilingual field (two inputs/textareas under the label)."""
    box = pg.locator(f"xpath=//*[normalize-space(text())='{label}']/ancestor::div[1]").first
    f = box.locator("input, textarea")
    f.nth(0).fill(ar); f.nth(1).fill(en)

